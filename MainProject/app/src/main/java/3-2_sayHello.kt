//Создайте функцию sayHello, которая принимает строковый аргумент name и
//возвращает приветственное сообщение. Функция должна иметь параметр по
//умолчанию "мир". Затем вызовите функцию дважды: с именем и без имени.

fun main() {
    println("Как вас зовут?")
    var a = readln()
    sayHello(a)
    sayHello()
}
fun sayHello(name: String = "мир") {
    println("Добрый день, $name!")
}

